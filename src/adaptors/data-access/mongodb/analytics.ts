import type { ClientSession, Db, Filter } from "mongodb";

import { randomUUID } from "node:crypto";

import type { AnalyticsDestination, CohortJoinedV1, PendingDelivery } from "~/entities/analytics";
import type {
  AnalyticsStore,
  ClaimedDelivery,
  ClaimOptions,
  ClaimRef,
  DeliveryDiagnostics,
  DeliveryFailure,
  DeliveryState,
  DeliverySummary,
  DeliveryTransition,
} from "~/interfaces/analytics";

import { analyticsMongoIndexes, analyticsTables } from "~/adaptors/setup/analyticsStorage";

import { isDuplicateKey } from "./store";

interface Binding {
  destination_key: string;
  provider: string;
}

interface Delivery extends Binding {
  event_id: string;
  event_json: string;
  subject_id: string;
  state: DeliveryState;
  attempts: number;
  created_at: number;
  due_at: number;
  lease_token: string | null;
  completed_at: number | null;
  failure_reason: DeliveryFailure | null;
}

function owned(ref: ClaimRef, now: number): Filter<Delivery> {
  return {
    event_id: ref.eventId,
    destination_key: ref.destinationKey,
    state: "claimed",
    lease_token: ref.leaseToken,
    due_at: { $gt: now },
  };
}

export default class MongoAnalyticsStore implements AnalyticsStore {
  private readonly bindings;
  private readonly deliveries;

  constructor(private readonly db: Db) {
    const options = { readPreference: "primary", writeConcern: { w: "majority" } } as const;
    this.bindings = db.collection<Binding>("xp_analytics_destinations", options);
    this.deliveries = db.collection<Delivery>("xp_analytics_deliveries", options);
  }

  async ready(destinations: readonly AnalyticsDestination[]): Promise<void> {
    try {
      for (const table of analyticsTables) {
        const indexes = await this.db.collection(table.name).listIndexes().toArray();
        for (const required of analyticsMongoIndexes(table)) {
          const index = indexes.find((item) => item.name === required.name);
          const keys = Object.fromEntries(required.fields.map((field) => [field, 1]));
          if (
            !index ||
            JSON.stringify(index.key) !== JSON.stringify(keys) ||
            Boolean(index.unique) !== required.unique ||
            index.partialFilterExpression ||
            index.sparse ||
            index.hidden ||
            index.expireAfterSeconds !== undefined
          )
            throw new Error(`Missing or incompatible ${required.name}`);
        }
      }
    } catch (cause) {
      throw new Error(
        "Apply the MongoDB analytics v1 bootstrap generated by xp setup --analytics before enabling capture or delivery.",
        { cause },
      );
    }
    for (const { key, provider } of destinations) {
      const filter = { destination_key: key };
      let binding: Binding | null;
      try {
        binding = await this.bindings.findOneAndUpdate(
          filter,
          { $setOnInsert: { provider } },
          { upsert: true, returnDocument: "after" },
        );
      } catch (error) {
        if (!isDuplicateKey(error)) throw error;
        binding = await this.bindings.findOne(filter);
      }
      if (binding?.provider !== provider)
        throw new Error(`Analytics destination ${key} is already bound to another provider.`);
    }
  }

  async insert(pending: readonly PendingDelivery[], session: ClientSession): Promise<void> {
    if (!pending.length) return;
    const bindings = pending.map(({ destinationKey, provider }) => ({
      destination_key: destinationKey,
      provider,
    }));
    if ((await this.bindings.countDocuments({ $or: bindings }, { session })) !== pending.length)
      throw new Error(
        "Analytics capture needs matching destination bindings. Check the analytics configuration and storage.",
      );
    await this.deliveries.insertMany(
      pending.map((delivery) => {
        const time = Date.parse(delivery.event.occurredAt);
        return {
          event_id: delivery.event.id,
          destination_key: delivery.destinationKey,
          provider: delivery.provider,
          subject_id: delivery.subjectId,
          event_json: JSON.stringify(delivery.event),
          state: "pending",
          attempts: 0,
          created_at: time,
          due_at: time,
          lease_token: null,
          completed_at: null,
          failure_reason: null,
        };
      }),
      { session },
    );
  }

  async claim(
    destination: AnalyticsDestination,
    { now, leaseMs, limit }: ClaimOptions,
  ): Promise<ClaimedDelivery[]> {
    const claimed: ClaimedDelivery[] = [];
    for (let i = 0; i < limit; i++) {
      const leaseToken = randomUUID();
      const leaseUntil = now + leaseMs;
      const doc = await this.deliveries.findOneAndUpdate(
        {
          destination_key: destination.key,
          provider: destination.provider,
          state: { $in: ["pending", "claimed"] },
          due_at: { $lte: now },
        },
        {
          $inc: { attempts: 1 },
          $set: { state: "claimed", lease_token: leaseToken, due_at: leaseUntil },
        },
        {
          sort: { due_at: 1 },
          hint: { destination_key: 1, state: 1, due_at: 1 },
          returnDocument: "after",
        },
      );
      if (!doc) break;
      claimed.push({
        event: JSON.parse(doc.event_json) as CohortJoinedV1,
        subjectId: doc.subject_id,
        destinationKey: doc.destination_key,
        provider: doc.provider,
        attempts: doc.attempts,
        leaseToken,
        leaseUntil,
      });
    }
    return claimed;
  }

  async settle(ref: ClaimRef, transition: DeliveryTransition, now: number): Promise<boolean> {
    const update = {
      state: transition.state,
      lease_token: null,
      completed_at: transition.state === "pending" ? null : now,
      due_at: transition.state === "pending" ? transition.availableAt : now,
      failure_reason: transition.state === "delivered" ? null : transition.reason,
    };
    return (await this.deliveries.updateOne(owned(ref, now), { $set: update })).matchedCount === 1;
  }

  async renew(ref: ClaimRef, leaseUntil: number, now: number): Promise<boolean> {
    if (leaseUntil <= now) return false;
    return (
      (await this.deliveries.updateOne(owned(ref, now), { $max: { due_at: leaseUntil } }))
        .matchedCount === 1
    );
  }

  async destinations(after: string | null, limit: number): Promise<AnalyticsDestination[]> {
    if (limit <= 0) return [];
    const page = await this.bindings
      .find(after === null ? {} : { destination_key: { $gt: after } })
      .sort({ destination_key: 1 })
      .limit(limit)
      .toArray();
    return page.map((row) => ({ key: row.destination_key, provider: row.provider }));
  }

  async inspect(
    destinationKey: string,
    state: DeliveryState,
    limit: number,
  ): Promise<DeliverySummary[]> {
    if (limit <= 0) return [];
    const page = await this.deliveries
      .find(
        { destination_key: destinationKey, state },
        {
          projection: {
            event_id: 1,
            destination_key: 1,
            provider: 1,
            created_at: 1,
            attempts: 1,
            state: 1,
            failure_reason: 1,
          },
        },
      )
      .sort({ created_at: 1 })
      .limit(limit)
      .toArray();
    return page.map((row) => ({
      eventId: row.event_id,
      destinationKey: row.destination_key,
      provider: row.provider,
      occurredAt: new Date(row.created_at).toISOString(),
      attempts: row.attempts,
      state: row.state,
      reason: row.failure_reason,
    }));
  }

  async diagnostics(destinationKey: string): Promise<DeliveryDiagnostics> {
    const groups = await this.deliveries
      .aggregate<{ _id: DeliveryState; count: number; oldest: number }>(
        [
          { $match: { destination_key: destinationKey } },
          { $group: { _id: "$state", count: { $sum: 1 }, oldest: { $min: "$created_at" } } },
        ],
        { hint: "xp_analytics_age_idx" },
      )
      .toArray();
    const counts = { pending: 0, claimed: 0, failed: 0, delivered: 0 };
    let oldestPendingAt: number | null = null;
    for (const group of groups) {
      counts[group._id] = group.count;
      if (group._id === "pending" || group._id === "claimed")
        oldestPendingAt = Math.min(oldestPendingAt ?? group.oldest, group.oldest);
    }
    return { counts, oldestPendingAt };
  }

  async redrive(destinationKey: string, eventId: string, now: number): Promise<boolean> {
    return (
      (
        await this.deliveries.updateOne(
          { destination_key: destinationKey, event_id: eventId, state: "failed" },
          {
            $set: {
              state: "pending",
              attempts: 0,
              due_at: now,
              lease_token: null,
              completed_at: null,
              failure_reason: null,
            },
          },
        )
      ).matchedCount === 1
    );
  }

  prune(destinationKey: string, before: number, limit: number): Promise<number> {
    return this.deletePage(
      {
        destination_key: destinationKey,
        state: { $in: ["delivered", "failed"] },
        completed_at: { $lt: before },
      },
      limit,
    );
  }

  purge(destinationKey: string, now: number, limit: number): Promise<number> {
    return this.deletePage(
      {
        destination_key: destinationKey,
        $or: [{ state: "pending" }, { state: "claimed", due_at: { $lte: now } }],
      },
      limit,
    );
  }

  private async deletePage(filter: Filter<Delivery>, limit: number): Promise<number> {
    if (limit <= 0) return 0;
    const ids = await this.deliveries
      .find(filter, { projection: { _id: 1 } })
      .limit(limit)
      .toArray();
    if (!ids.length) return 0;
    // A worker or operator may have changed the state between selection and deletion.
    return (
      await this.deliveries.deleteMany({ ...filter, _id: { $in: ids.map((doc) => doc._id) } })
    ).deletedCount;
  }
}
