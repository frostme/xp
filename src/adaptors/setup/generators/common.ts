import { posix } from "node:path";

import type { ProjectDetection, ResolvedSetup } from "~/interfaces/setup";

export const generatedHeader = "// Generated by xp setup (storage v1). Review before applying.\n";
export const sqlHeader = "-- Generated by xp setup (storage v1). Review before applying.\n";
export const migrationStamp = () => new Date().toISOString().replace(/\D/g, "").slice(0, 14);
export const outputPath = (directory: string, filename: string) =>
  posix.join(directory.replaceAll("\\", "/"), filename);
export function codeExtension(options: ResolvedSetup): string {
  return options.language === "typescript"
    ? "ts"
    : options.moduleFormat === "commonjs"
      ? "cjs"
      : "js";
}
export function command(project: ProjectDetection, binary: string): string {
  return project.packageManager === "bun"
    ? `bun run ${binary}`
    : project.packageManager === "pnpm"
      ? `pnpm exec ${binary}`
      : project.packageManager === "yarn"
        ? `yarn exec ${binary}`
        : `npm exec --no -- ${binary}`;
}
export function nativeGuidance(options: ResolvedSetup): string {
  const driver = {
    postgres: "pg.Client or pg.Pool",
    mysql: "a mysql2/promise connection or pool",
    mssql: "a connected mssql.ConnectionPool",
    mongodb: "MongoClient with an explicit databaseName",
    dynamodb: "DynamoDBDocumentClient with an explicit tableName",
  }[options.database];
  return `Pass ${driver} to xp/server; ORM instances are not supported runtime clients. Create application user records before assigning experiments.`;
}
export function userPrimitive(options: ResolvedSetup): "string" | "number" {
  return /^(?:number|tinyint|smallint|mediumint|int|integer)\b/i.test(options.userIdType)
    ? "number"
    : "string";
}

/** Quote a literal argument for the documented POSIX shell commands. */
export function shellQuote(value: string): string {
  return "'" + value.replaceAll("'", "'\"'\"'") + "'";
}
